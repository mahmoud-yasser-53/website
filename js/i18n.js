let currentLang = "en";

function getTranslations() {
  return translations[currentLang];
}

function setLanguage(lang) {
  currentLang = lang;
  const t = translations[lang];
  document.documentElement.setAttribute("dir", t.dir);
  document.documentElement.setAttribute("lang", lang);
  applyTranslations(t);
  updateLangToggleButtons(t);
  renderDynamicSections(t);
}

function applyTranslations(t) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = getNestedValue(t, key);
    if (value !== undefined) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    const value = getNestedValue(t, key);
    if (value !== undefined) el.placeholder = value;
  });

  const themeBtn = document.getElementById("theme-toggle");
  const themeBtnMobile = document.getElementById("theme-toggle-mobile");
  const theme = document.documentElement.classList.contains("dark") ? "dark" : "light";
  const title = theme === "light" ? t.themeLight : t.themeDark;
  if (themeBtn) themeBtn.title = title;
  if (themeBtnMobile) themeBtnMobile.title = title;
}

function getNestedValue(obj, path) {
  return path.split(".").reduce((acc, part) => acc && acc[part], obj);
}

function updateLangToggleButtons(t) {
  document.querySelectorAll("[data-lang-toggle]").forEach((btn) => {
    btn.textContent = currentLang === "en" ? t.langToggle : (currentLang === "ar" ? "English" : "EN");
  });
}

function renderDynamicSections(t) {
  renderStats("stats-bar", t.stats);
  renderStats("about-stats", t.stats);
  renderServices(t.services.items);
  renderServiceOptions(t.contact);
  updateMobileMenuLabel();
}

function renderStats(containerId, stats) {
  const container = document.getElementById(containerId);
  if (!container) return;
  const isCard = containerId === "about-stats";
  container.innerHTML = stats
    .map(
      (s, i) => `
    <div class="fade-in ${isCard ? "stat-card" : "stat-item"}" style="animation-delay: ${i * 0.08}s">
      <p class="stat-value gradient-text">${s.value}</p>
      <p class="stat-label">${s.label}</p>
    </div>`
    )
    .join("");
}

function renderServices(items) {
  const container = document.getElementById("services-list");
  if (!container) return;
  container.innerHTML = items
    .map(
      (s, i) => `
    <div class="service-item fade-in" style="animation-delay: ${i * 0.08}s">
      <h3 class="service-title">${s.title}</h3>
      <p class="service-desc">${s.desc}</p>
    </div>`
    )
    .join("");
}

function renderServiceOptions(contact) {
  const select = document.getElementById("service");
  if (!select) return;
  const current = select.value;
  select.innerHTML =
    `<option value="">${contact.ph_service}</option>` +
    contact.serviceOptions.map((o) => `<option value="${o}">${o}</option>`).join("");
  if (current) select.value = current;
}

function updateMobileMenuLabel() {
  const btn = document.getElementById("mobile-menu-toggle");
  if (!btn) return;
  const t = getTranslations();
  const isOpen = btn.getAttribute("aria-expanded") === "true";
  btn.textContent = isOpen ? t.nav.close : t.nav.menu;
}

function toggleLanguage() {
  setLanguage(currentLang === "en" ? "ar" : "en");
}

function initI18n() {
  setLanguage("en");
}
